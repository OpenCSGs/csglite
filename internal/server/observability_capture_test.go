func TestObservationMultipartCapturePreservesLargeUploadAndLateModel(t *testing.T) {
	var body bytes.Buffer
	form := multipart.NewWriter(&body)
	file, err := form.CreateFormFile("file", "audio.wav")
	if err != nil {
		t.Fatal(err)
	}
	_, _ = io.WriteString(file, strings.Repeat("private-audio", observabilityBodyLimit/6))
	_ = form.WriteField("model", "public-asr")
	_ = form.WriteField("source", "pool:asr")
	_ = form.WriteField("api_key", "upload-secret")
	_ = form.WriteField("stream", "true")
	_ = form.Close()
	original := append([]byte(nil), body.Bytes()...)
	r := httptest.NewRequest(http.MethodPost, "/ai-gateway/v1/audio/transcriptions", &body)
	r.Header.Set("Content-Type", form.FormDataContentType())
	capture := captureObservationRequest(r)
	defer capture.finish()
	forwarded, err := io.ReadAll(r.Body)
	if err != nil || !bytes.Equal(forwarded, original) {
		t.Fatal("observability changed multipart upload", err)
	}
	capture.finish()
	stored := string(sanitizeObservationBody(capture.body.Bytes()))
	if !strings.Contains(stored, "public-asr") || !strings.Contains(stored, "audio.wav") || strings.Contains(stored, "private-audio") || strings.Contains(stored, "upload-secret") {
		t.Fatalf("invalid multipart capture: %s", stored)
	}
	if !observationRequestStreams(capture.body.Bytes()) || capture.body.Len() > 1024 {
		t.Fatal("upload metadata lost stream flag or grew with file size")
	}
}

func TestObservationJSONCaptureIsBoundedAndReplaysCompleteBody(t *testing.T) {
	body := `{"model":"large","input":"` + strings.Repeat("x", observabilityBodyLimit*2) + `"}`
	r := httptest.NewRequest(http.MethodPost, "/v1/embeddings", strings.NewReader(body))
	capture := captureObservationRequest(r)
	defer capture.finish()
	forwarded, err := io.ReadAll(r.Body)
	if err != nil || string(forwarded) != body || !capture.truncated || capture.body.Len() != observabilityBodyLimit {
		t.Fatal("bounded observation changed the request or did not enforce its capture limit", err)
	}
	secret := sanitizeObservationBody([]byte(`{"api_key":"truncated-secret`))
	if bytes.Contains(secret, []byte("truncated-secret")) {
		t.Fatal("partial JSON exposed a credential")
	}
}

func TestObservedModalitiesAndExcludedControlEndpoints(t *testing.T) {
	for _, path := range []string{"embeddings", "images/generations", "images/edits", "audio/transcriptions", "audio/speech"} {
		for _, prefix := range []string{"/v1/", "/ai-gateway/v1/", "/providers/test/v1/"} {
			r := httptest.NewRequest(http.MethodPost, prefix+path, nil)
			if !isObservedRequest(r) || observationProtocol(r.URL.Path) != path {
				t.Fatalf("missing modality: %s", r.URL.Path)
			}
		}
	}
	for _, path := range []string{"/api/load", "/api/pull", "/v1/messages/count_tokens", "/ai-gateway/v1/messages/count_tokens", "/v1/realtime/calls"} {
		if isObservedRequest(httptest.NewRequest(http.MethodPost, path, nil)) {
			t.Fatalf("control or session handshake counted as completed inference: %s", path)
		}
	}
}

func TestObservationGeneratedPayloadOmissionKeepsFailures(t *testing.T) {
	for _, path := range []string{"embeddings", "images/generations", "images/edits", "audio/speech"} {
		t.Run(path, func(t *testing.T) {
			s := newTestServer(t)
			for _, status := range []int{http.StatusOK, http.StatusBadRequest} {
				h := s.observabilityMiddleware(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
					w.Header().Set("Content-Type", "application/json")
					w.WriteHeader(status)
					if status == http.StatusOK {
						_, _ = io.WriteString(w, `{"data":"private-generated-content"}`)
					} else {
						_, _ = io.WriteString(w, `{"error":{"message":"inference failed"}}`)
					}
				}))
				r := httptest.NewRequest(http.MethodPost, "/ai-gateway/v1/"+path, strings.NewReader(`{"model":"service"}`))
				w := httptest.NewRecorder()
				h.ServeHTTP(w, r)
				record, err := s.observability.GetRequest(r.Context(), w.Header().Get(observabilityRequestIDHeader))
				if err != nil {
					t.Fatal(err)
				}
				if status == http.StatusOK && (strings.Contains(record.ResponseBody, "private-generated-content") || !strings.Contains(record.ResponseBody, `"payload_omitted":true`)) {
					t.Fatal("generated bytes stored in observation")
				}
				if status == http.StatusBadRequest && record.ErrorMessage != "inference failed" {
					t.Fatalf("failure was hidden by payload omission: %+v", record)
				}
				if !strings.Contains(w.Body.String(), map[bool]string{true: "private-generated-content", false: "inference failed"}[status == http.StatusOK]) {
					t.Fatal("observation modified client response")
				}
				var body any
				if json.Unmarshal([]byte(record.ResponseBody), &body) != nil {
					t.Fatal("observation payload is not valid JSON")
				}
			}
		})
	}
}
